export function getT(langCode: string = 'hi') {
  const code = (langCode in {
    hi: 1, en: 1, mr: 1, te: 1, ta: 1, bn: 1, gu: 1, kn: 1, ml: 1, pa: 1, or: 1, as: 1, ur: 1
  } ? langCode : 'hi') as SupportedLanguage;

  return (key: string, fallback?: string): string => {
    const entry = DASHBOARD_TRANSLATIONS[key];
    if (!entry) return fallback || key;
    return entry[code] || entry['hi'] || entry['en'] || fallback || key;
  };
}
